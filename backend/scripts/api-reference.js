/**
 * Writes docs/API.md from the routes themselves.
 *
 *   npm run docs:api            rewrite the reference
 *   npm run docs:api -- --check fail if the reference is out of date (CI)
 *
 * A hand-written API reference is wrong by the second release. This one reads
 * the mount table in src/app.js, the roles each route's requireRole was given
 * and the fields its validate schema checks, so a route cannot change without
 * the reference changing with it.
 */
const fs = require('fs');
const path = require('path');

const { MOUNTS } = require('../src/app');

const OUT = path.join(__dirname, '..', '..', 'docs', 'API.md');
const CHECK = process.argv.includes('--check');

const who = (roles, isPublic) => {
  if (isPublic) return 'Anyone';
  if (!roles) return 'Any signed-in user';
  return roles.map((role) => (role === 'ADMIN' ? 'Admin' : role.charAt(0) + role.slice(1).toLowerCase())).join(', ');
};

const fieldList = (schema) => {
  if (!schema) return '';

  return Object.entries(schema)
    .map(([name, rule]) => {
      const bits = [];
      if (rule.type) bits.push(rule.type);
      if (rule.oneOf) bits.push(rule.oneOf.join(' / '));
      if (rule.isList) bits.push('list');
      return `\`${name}\`${rule.required ? '' : '?'}${bits.length ? ` (${bits.join(', ')})` : ''}`;
    })
    .join(', ');
};

const expensivePrefixes = MOUNTS.filter((mount) => mount.limit === 'expensive').map((mount) => mount.path);

const sections = [];
let total = 0;

for (const mount of MOUNTS.filter((entry) => entry.router)) {
  const rows = [];
  let routerRoles = null;

  for (const layer of mount.router.stack) {
    // router.use(requireRole(...)) applies to every route declared after it.
    if (!layer.route) {
      if (layer.handle && layer.handle.roles) routerRoles = layer.handle.roles;
      continue;
    }

    const handles = layer.route.stack.map((entry) => entry.handle);
    const roles = (handles.find((handle) => handle.roles) || {}).roles || routerRoles;
    const schema = (handles.find((handle) => handle.schema) || {}).schema;
    const full = `${mount.path}${layer.route.path === '/' ? '' : layer.route.path}`;
    const slow = expensivePrefixes.some((prefix) => full === prefix || full.startsWith(`${prefix}/`));

    for (const method of Object.keys(layer.route.methods).filter((m) => m !== '_all')) {
      const open = mount.public && !handles.some((handle) => handle.requiresSignIn);
      rows.push(`| ${method.toUpperCase()} | \`${full}\`${slow ? ' (limited)' : ''} | ${who(roles, open)} | ${fieldList(schema)} |`);
      total += 1;
    }
  }

  sections.push(
    [`## \`${mount.path}\``, '', '| Method | Path | Who | Body |', '| :--- | :--- | :--- | :--- |', ...rows, ''].join('\n')
  );
}

const document = [
  '# LogApart API reference',
  '',
  '<!-- Generated by backend/scripts/api-reference.js. Do not edit by hand: run `npm run docs:api`. -->',
  '',
  `${total} routes. Every path except \`/api/auth\` and the health checks needs a`,
  '`Bearer` token and a password that is no longer the one-time one. Responses are',
  '`{ success, data?, message? }`; a refused body comes back `400` with `code:',
  'INVALID_REQUEST` and every problem in `errors`.',
  '',
  '- **Who:** roles the route admits. `Admin` includes every administrative role. A',
  '  controller can narrow this further, for example to the home of the caller.',
  '- **Body:** fields the validator checks. `?` marks an optional field.',
  '- **(limited):** the tighter rate limit applies on top of the standard 300 a minute.',
  '',
  '## Health',
  '',
  '| Method | Path | Who | Body |',
  '| :--- | :--- | :--- | :--- |',
  '| GET | `/api/health` | Anyone | |',
  '| GET | `/api/health/ready` | Anyone | |',
  '',
  ...sections,
  '## Changes',
  '',
  '- **Units.** `GET /api/units` returns the flat list of homes as `homeList`. Before',
  '  September 2026 the same list was called `flatList`. The API is not versioned and',
  '  has one client, the web app in this repository, which was changed in the same',
  '  commit; any other client must read `homeList`.',
  ''
].join('\n');

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';

  if (current !== document) {
    console.error('docs/API.md is out of date. Run npm run docs:api and commit the result.');
    process.exit(1);
  }

  console.log(`docs/API.md is current, ${total} routes.`);
  process.exit(0);
}

fs.writeFileSync(OUT, document);
console.log(`Wrote docs/API.md, ${total} routes.`);
process.exit(0);
